


// Relational Operators


#include <iostream>
using namespace std;
int main(){
    int a = 10;
    int b = 15;

    cout <<(a==b) << endl;
    cout << ( a> b) << endl;
    cout << (a < b) <<  endl;
    cout << ( a >= b) << endl;
    cout << ( a <=b) << endl;
    cout << (a!= b ) << endl;
return 0;
}